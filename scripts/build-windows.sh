#!/usr/bin/env bash
# Windows packaging: portable zip, NSIS installer, optional MSI (WiX), and
# Authenticode signing. Runs under Git Bash / MSYS on a Windows runner, which
# is why it is bash like every other script here (one language, one lint).
#
# WHY NSIS as the primary installer and MSI as secondary: NSIS produces a
# small self-contained installer with no runtime prerequisites and is what
# most Rust desktop tools ship (including Handy via Tauri). MSI matters for
# enterprise deployment (GPO/Intune push), so we emit it when WiX is present
# but do not fail the release when it is not.
#
# Authenticode / SmartScreen reality check, documented here because it is a
# business decision as much as a technical one:
#   - An UNSIGNED exe gets the harshest SmartScreen wall and some AVs
#     quarantine it outright. Not shippable.
#   - An OV certificate signs validly but SmartScreen reputation starts at
#     zero PER CERTIFICATE and builds with install volume over weeks. Early
#     users still click through "More info -> Run anyway".
#   - An EV certificate (or the newer Azure Trusted Signing service) grants
#     reputation immediately. For a tool that injects input - exactly the
#     behaviour malware heuristics look for - EV/Trusted Signing is the only
#     path that avoids weeks of scary warnings. Budget it like the Apple
#     Developer ID: an onboarding cost, not a distribution nicety.
#
# Signing env (CI provides via secrets; absent locally -> unsigned artifacts,
# clearly labelled):
#   WINDOWS_CERT_THUMBPRINT  thumbprint of a cert in the runner's cert store
#                            (imported by the workflow from a base64 secret),
#                            signed via signtool /sha1.
#
# The pre-Haswell AVX2 crash class: nothing in THIS script guards it because
# the guard belongs earlier, at compile time. See .cargo/config.toml (no
# target-cpu raise anywhere) and deny.toml (bans `ort`'s prebuilt runtime).
# ci-verify-baseline.sh disassembles the shipped exe to prove no AVX2 leaked
# into static initializers. docs/build-and-release.md#windows has the story.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

TARGET="${1:-x86_64-pc-windows-msvc}"   # or aarch64-pc-windows-msvc
VERSION="$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)"
OUT="dist/windows/$TARGET"
BIN="target/$TARGET/release/spike-cli.exe"
# The dictation daemon: the thing a user actually runs. It is a separate
# artifact from the spike harness because they answer different questions
# ("does this machine work" vs "dictate for me"), and shipping only the
# harness, as this script did while the Windows backends were stubs, would
# mean a Windows release that cannot dictate.
DAEMON="target/$TARGET/release/outloud.exe"

echo "==> Building $TARGET"
rustup target add "$TARGET"

# --features outloud/whisper: the recognizer itself. Without it the daemon
# BUILDS fine, STARTS fine, downloads a model on first run, and then errors
# on every single utterance with "this build has no whisper backend" --
# whisper.cpp is the only recognizer that exists off macOS, and the feature
# is off by default so plain typechecks do not need cmake. A release
# without it is a dictation app that cannot transcribe, which is exactly
# what this script shipped until 2026-10-21. The windows-2025 runners have
# cmake and MSVC, so the from-source whisper.cpp build just works.
cargo build --release --locked --package spike-cli --package outloud \
    --features outloud/whisper --target "$TARGET"

mkdir -p "$OUT"
cp "$BIN" "$OUT/outloud-spike.exe"
cp "$DAEMON" "$OUT/outloud.exe"

sign() {
    local file="$1"
    if [ -n "${WINDOWS_CERT_THUMBPRINT:-}" ]; then
        echo "==> Authenticode signing $file"
        # /fd sha256: SHA-1 signatures are rejected by modern Windows.
        # /td sha256 /tr: RFC3161 timestamp so the signature outlives the
        # certificate. Without a timestamp, every shipped binary breaks the
        # day the cert expires.
        signtool sign /sha1 "$WINDOWS_CERT_THUMBPRINT" /fd sha256 \
            /tr http://timestamp.digicert.com /td sha256 "$file"
        signtool verify /pa "$file"
    else
        echo "==> WINDOWS_CERT_THUMBPRINT unset: NOT signing $file (SmartScreen will wall this build)"
    fi
}

sign "$OUT/outloud-spike.exe"
sign "$OUT/outloud.exe"

echo "==> Portable zip"
(cd "$OUT" && 7z a -tzip "outloud-spike-$VERSION-$TARGET.zip" outloud-spike.exe outloud.exe >/dev/null)

if command -v makensis >/dev/null 2>&1; then
    echo "==> NSIS installer"
    cat > "$OUT/installer.nsi" <<NSIS
; Generated by build-windows.sh.
;
; This installs the PRODUCT (the outloud dictation daemon), not just the
; spike harness it originally shipped. What each piece is for:
;   - Start Menu shortcut: without one the app is unlaunchable except by
;     finding the exe in Explorer; OutLoud has no Desktop icon by design
;     (it is a background tool, the tray is its surface).
;   - Launch checkbox on the finish page: the tray icon appearing right
;     after install is what tells the user the install worked.
;   - No autostart section here: launch-at-login is a PRODUCT setting
;     (config.toml, synced to the HKCU Run key by the daemon itself, with
;     a tray toggle). An installer checkbox would be a second writer to
;     the same registry value that the daemon would immediately fight.
!include "MUI2.nsh"
Name "OutLoud"
OutFile "outloud-$VERSION-$TARGET-setup.exe"
InstallDir "\$LOCALAPPDATA\\OutLoud"
RequestExecutionLevel user   ; per-user install: no UAC prompt, no admin
!define MUI_FINISHPAGE_RUN "\$INSTDIR\\outloud.exe"
!define MUI_FINISHPAGE_RUN_TEXT "Start OutLoud now"
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_PAGE_FINISH
!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_LANGUAGE "English"
Section "Install"
    SetOutPath "\$INSTDIR"
    File "outloud.exe"
    File "outloud-spike.exe"
    CreateDirectory "\$SMPROGRAMS\\OutLoud"
    CreateShortCut "\$SMPROGRAMS\\OutLoud\\OutLoud.lnk" "\$INSTDIR\\outloud.exe"
    WriteUninstaller "\$INSTDIR\\uninstall.exe"
    WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\OutLoud" "DisplayName" "OutLoud"
    WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\OutLoud" "DisplayVersion" "$VERSION"
    WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\OutLoud" "DisplayIcon" "\$INSTDIR\\outloud.exe"
    WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\OutLoud" "UninstallString" "\$INSTDIR\\uninstall.exe"
SectionEnd
Section "Uninstall"
    ; A running daemon holds a lock on its own exe; stop it first. /f
    ; because the daemon has no WM_CLOSE surface (message-only windows),
    ; and its state is all in config files it only reads.
    ExecWait 'taskkill /im outloud.exe /f'
    ; The daemon's own launch-at-login Run value, so an uninstalled app
    ; cannot be relaunched at next boot.
    DeleteRegValue HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Run" "OutLoud"
    Delete "\$SMPROGRAMS\\OutLoud\\OutLoud.lnk"
    RMDir "\$SMPROGRAMS\\OutLoud"
    Delete "\$INSTDIR\\outloud-spike.exe"
    Delete "\$INSTDIR\\outloud.exe"
    Delete "\$INSTDIR\\uninstall.exe"
    RMDir "\$INSTDIR"
    DeleteRegKey HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\OutLoud"
SectionEnd
NSIS
    (cd "$OUT" && makensis installer.nsi)
    sign "$OUT/outloud-$VERSION-$TARGET-setup.exe"
else
    echo "==> makensis not found: skipping NSIS installer"
fi

if command -v wix >/dev/null 2>&1; then
    echo "==> MSI via WiX v4"
    cat > "$OUT/package.wxs" <<WXS
<?xml version="1.0" encoding="UTF-8"?>
<!-- Minimal per-user MSI for enterprise deployment tooling. UpgradeCode is
     fixed forever: changing it orphans installed copies from upgrades. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Package Name="OutLoud Spike" Manufacturer="OutLoud" Version="$VERSION"
           UpgradeCode="7f9b2a44-1c3e-4d5f-9a8b-0e6f31c25a10" Scope="perUser">
    <MajorUpgrade DowngradeErrorMessage="A newer version is already installed." />
    <StandardDirectory Id="LocalAppDataFolder">
      <Directory Id="INSTALLFOLDER" Name="OutLoud">
        <Component Id="MainExe">
          <File Source="outloud-spike.exe" />
          <RegistryValue Root="HKCU" Key="Software\\OutLoud" Name="installed"
                         Type="integer" Value="1" KeyPath="yes" />
        </Component>
        <Component Id="DaemonExe">
          <File Source="outloud.exe" />
          <RegistryValue Root="HKCU" Key="Software\\OutLoud" Name="daemon"
                         Type="integer" Value="1" KeyPath="yes" />
        </Component>
      </Directory>
    </StandardDirectory>
    <Feature Id="Main"><ComponentRef Id="MainExe" /><ComponentRef Id="DaemonExe" /></Feature>
  </Package>
</Wix>
WXS
    (cd "$OUT" && wix build package.wxs -o "outloud-spike-$VERSION-$TARGET.msi")
    sign "$OUT/outloud-spike-$VERSION-$TARGET.msi"
else
    echo "==> wix not found: skipping MSI (NSIS installer is the primary artifact)"
fi

ls -l "$OUT"
